// Turns data/eff_large_wordlist.txt (as published by the EFF) into a TypeScript
// module. The dice numbers are dropped: the generator picks an index with
// crypto.getRandomValues, so only the order of the 7,776 words matters.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const raw = readFileSync(`${root}data/eff_large_wordlist.txt`);
const sha256 = createHash("sha256").update(raw).digest("hex");

const words = raw
  .toString("utf8")
  .split(/\r?\n/)
  .filter(Boolean)
  .map((line) => {
    const m = /^([1-6]{5})\t([a-z-]+)$/.exec(line);
    if (!m) throw new Error(`Unexpected line: ${JSON.stringify(line)}`);
    return m[2];
  });

if (words.length !== 7776) throw new Error(`Expected 7776 words, got ${words.length}`);
if (new Set(words).size !== words.length) throw new Error("Duplicate words in list");

const out = `// Generated by scripts/make-wordlist.mjs. Do not edit.
//
// EFF Large Wordlist for passphrases, published by the Electronic Frontier
// Foundation at https://www.eff.org/dice (file:
// https://www.eff.org/files/2016/07/18/eff_large_wordlist.txt).
// Licensed CC BY 4.0, per https://www.eff.org/copyright.
// Source file SHA-256: ${sha256}

export const EFF_LARGE_WORDLIST_SHA256 = "${sha256}";

export const EFF_LARGE_WORDLIST: readonly string[] = ${JSON.stringify(words.join(" "))}.split(" ");
`;

writeFileSync(`${root}src/core/eff-large-wordlist.ts`, out);
process.stdout.write(`Wrote ${words.length} words (sha256 ${sha256})\n`);
